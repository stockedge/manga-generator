import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {fileURLToPath,pathToFileURL} from 'node:url';
import crypto from 'node:crypto';
const root=path.dirname(fileURLToPath(import.meta.url));
fs.mkdirSync(path.join(root,'tmp'),{recursive:true});
const fixture=fs.mkdtempSync(path.join(root,'tmp','automatic-'));
for(const file of ['auto.mjs','new-work.mjs','quality.mjs','face-design.mjs','state-history.mjs','stage-reviews.mjs'])fs.copyFileSync(path.join(root,file),path.join(fixture,file));
const run=(args,project)=>execFileSync(process.execPath,[path.join(fixture,'auto.mjs'),...args],{cwd:fixture,env:{...process.env,MANGA_PROJECT:project||''},encoding:'utf8',stdio:'pipe',windowsHide:true});
const original=path.join(fixture,'original.txt'),text='一人の店主が手紙を受け取る。\n「また会おう」\n翌朝、店を出た。';
const digest=b=>crypto.createHash('sha256').update(b).digest('hex');
fs.writeFileSync(original,'\uFEFF'+text);
const expected=`works/auto-${digest(Buffer.from(text)).slice(0,12)}/workflow.json`;
assert.match(run(['start',original]),/Prepared:/);
const full=path.join(fixture,expected),first=fs.readFileSync(full);
assert.equal(fs.readFileSync(path.join(path.dirname(full),'source','original.txt'),'utf8'),text);
assert.equal(JSON.parse(first).renderMode,'panels');
assert.match(run(['start',original]),/Resume:/);
assert.deepEqual(fs.readFileSync(full),first,'Resume overwrote script');
assert.throws(()=>run(['start',original,'--title','different']));
const empty=path.join(fixture,'empty.txt');fs.writeFileSync(empty,' ');assert.throws(()=>run(['start',empty]));
const invalid=path.join(fixture,'invalid.txt');fs.writeFileSync(invalid,Buffer.from([0xff,0xfe]));assert.throws(()=>run(['start',invalid]));
assert.throws(()=>run(['status']));assert.throws(()=>run(['status'],'../outside.json'));
assert.equal(JSON.parse(run(['status'],expected)).status,'needs-script-or-references','Intake cannot be marked complete');
assert.throws(()=>run(['finish'],expected),'Missing source coverage passed');
const coverage=path.join(path.dirname(full),'workflow','source-coverage.json');
const save=v=>fs.writeFileSync(coverage,JSON.stringify(v));
save({sourceHash:digest(Buffer.from(text)),spans:[{start:1,end:text.length,panels:['01-1'],adaptation:'店主の出発までの出来事を絵で描く'}]});
assert.throws(()=>run(['finish'],expected),e=>String(e.stderr).includes('Source coverage has a gap or overlap'),'Gap in source coverage passed');
save({sourceHash:digest(Buffer.from(text)),spans:[{start:0,end:text.length,panels:['unknown'],adaptation:'店主の出発までの出来事を絵で描く'}]});
assert.throws(()=>run(['finish'],expected),e=>String(e.stderr).includes('Coverage needs actual panels'),'Nonexistent source panel passed');
save({sourceHash:digest(Buffer.from(text)),spans:[{start:0,end:text.length-1,panels:['01-1'],adaptation:'店主の出発までの出来事を絵で描く'}]});
assert.throws(()=>run(['finish'],expected),e=>String(e.stderr).includes('Cover the entire supplied original'),'Truncated source coverage passed');
save({sourceHash:digest(Buffer.from(text)),spans:[{start:0,end:text.length,panels:['01-1'],adaptation:'店主の出発までの出来事を絵で描く'}]});
assert.throws(()=>run(['finish'],expected),e=>String(e.stderr).includes('generation-log.json'),'Missing generation evidence passed');
const logPath=path.join(path.dirname(full),'workflow','generation-log.json');
const panelIds=JSON.parse(fs.readFileSync(full,'utf8')).pages.flatMap(p=>p.panels.map(q=>q.id));
const writeLog=r=>fs.writeFileSync(logPath,JSON.stringify({sourceHash:digest(Buffer.from(text)),panels:panelIds.map(id=>({panel:id,renderer:r}))}));
writeLog('unreviewed-renderer');
assert.throws(()=>run(['finish'],expected),e=>String(e.stderr).includes('renderer'),'Undeclared renderer passed');
const declared=JSON.parse(fs.readFileSync(full,'utf8'));declared.generation={renderer:'unreviewed-renderer'};fs.writeFileSync(full,JSON.stringify(declared));
assert.throws(()=>run(['finish'],expected),e=>!String(e.stderr).includes('renderer'),'Declared renderer failed its own check');
fs.rmSync(logPath);
fs.appendFileSync(path.join(path.dirname(full),'source','original.txt'),'変更');
assert.throws(()=>run(['status'],expected),'Changed original passed');
assert.ok(!fs.existsSync(path.join(path.dirname(full),'automation.json')),'Test falsely completed a work');
// Isolated status fixture: enforce chunked archive reads and reject corruption.
fs.writeFileSync(path.join(path.dirname(full),'source','original.txt'),text);
fs.writeFileSync(path.join(fixture,'workflow.mjs'),"console.log('01: ready');\n");
fs.writeFileSync(path.join(fixture,'reproduce.mjs'),"console.log('fixture reproduction check');\n");
const archive=path.join(fixture,'archive.tar.gz'),bytes=Buffer.alloc(3*1024*1024+17,0x5a);
bytes[bytes.length-1]=0x31;fs.writeFileSync(archive,bytes);
const completion=path.join(path.dirname(full),'automation.json');
fs.writeFileSync(completion,JSON.stringify({status:'complete',deliverables:{'archive.tar.gz':digest(bytes)}}));
const guard=path.join(fixture,'guard-archive-read.mjs');
fs.writeFileSync(guard,"import fs from 'node:fs';const read=fs.readFileSync;fs.readFileSync=function(f,...args){if(String(f).endsWith('archive.tar.gz'))throw new Error('Whole archive read forbidden');return read.call(this,f,...args);};\n");
const guardedStatus=()=>JSON.parse(execFileSync(process.execPath,['--import',pathToFileURL(guard).href,path.join(fixture,'auto.mjs'),'status'],{cwd:fixture,env:{...process.env,MANGA_PROJECT:expected},encoding:'utf8',windowsHide:true}));
assert.equal(guardedStatus().status,'complete','Chunked hashing must handle multiple chunks and the final short chunk');
const fd=fs.openSync(archive,'r+');fs.writeSync(fd,Buffer.from([0x32]),0,1,bytes.length-1);fs.closeSync(fd);
assert.equal(guardedStatus().status,'in-progress','Corrupted archive passed');
fs.unlinkSync(archive);
assert.equal(guardedStatus().status,'in-progress','Missing archive passed');
fs.unlinkSync(completion);
console.log('PASS: automatic intake, BOM/UTF-8, stable resume, isolated works, explicit selection, coverage gaps, changed-source rejection and chunked archive hash/corruption/missing checks; status stubs are isolated fixtures, no actual work completed');
